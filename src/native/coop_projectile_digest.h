#pragma once
// Scalar Ex state proved against the original constructors/setup/update paths.
// See docs/audit-projectile-digest.md for offsets, exclusions and remaining gaps.
namespace coop_projectile_digest {
struct Field { uint32_t flag,offset; };
template<class Hash> static void Append(Hash& hash,uintptr_t bullet,uint32_t flags){
 static const Field timers[]={
  {1,0x700},{4,0x734},{8,0x768},{0x70,0x79c},{0x1000,0x804},
  {0x20000,0x838},{0x40000,0x86c},{0x800000,0x8a0},
  {0x2000000,0x8d4},{0x8000000,0x908},{0x20000000,0x93c},{0x400,0x970}
 };
 // Each timer contains three scalar values followed by a process-local pointer.
 for(auto field:timers)if(flags&field.flag)hash.words(bullet+field.offset,12);
 static const Field operands[]={
  {4,0x748},{4,0x750},{4,0x754},{4,0x758},{4,0x75c},
  {8,0x77c},{8,0x780},{8,0x790},
  {0x70,0x7b0},{0x70,0x7b4},{0x70,0x7c4},{0x70,0x7c8},{0x70,0x7cc},
  {0x100,0x7e4},{0x100,0x7f8},{0x100,0x7fc},{0x100,0x800},
  {0x800000,0x8b4},{0x800000,0x8b8},{0x800000,0x8c8},
  {0x2000000,0x8e8},{0x2000000,0x8f0},{0x2000000,0x8f4},{0x2000000,0x8f8},{0x2000000,0x8fc},
  {0x8000000,0x924},{0x8000000,0x928},{0x8000000,0x92c},{0x8000000,0x930},
  {0x20000000,0x950},{0x20000000,0x958},{0x20000000,0x95c},{0x20000000,0x960},{0x20000000,0x964},
  {0x400,0x998}
 };
 for(auto field:operands)if(flags&field.flag)hash.words(bullet+field.offset,4);
 if(flags&0x2000000){
  hash.words(bullet+0x9a8,0x3c); // Interpolation values and timer, no +0x9E4 pointer.
  hash.words(bullet+0x9ec,8);
 }
}
}
